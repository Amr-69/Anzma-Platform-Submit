BEGIN;

-- Reference tables
CREATE TABLE buildings (
    building_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        TEXT NOT NULL UNIQUE
);

CREATE TABLE locations (
    location_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    building_id BIGINT NOT NULL REFERENCES buildings(building_id),
    floor       INTEGER NOT NULL,
    name        TEXT NOT NULL,
    UNIQUE (building_id, name)
);

CREATE TABLE system_types (
    system_type_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code           TEXT NOT NULL UNIQUE
        CHECK (code IN ('HVAC','NETWORKING','ACCESS_CONTROL','CCTV','FIRE_ALARM'))
);

CREATE TABLE assets (
    asset_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_code     TEXT NOT NULL UNIQUE,
    name           TEXT NOT NULL,
    asset_type     TEXT NOT NULL,
    system_type_id BIGINT NOT NULL REFERENCES system_types(system_type_id),
    location_id    BIGINT NOT NULL REFERENCES locations(location_id)
);

CREATE TABLE metric_types (
    metric_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name      TEXT NOT NULL UNIQUE,
    unit      TEXT NOT NULL
);

CREATE TABLE event_types (
    event_type_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          TEXT NOT NULL UNIQUE
);

-- Compatibility tables (NEW)
CREATE TABLE metric_type_system_compat (
    metric_id      BIGINT NOT NULL REFERENCES metric_types(metric_id),
    system_type_id BIGINT NOT NULL REFERENCES system_types(system_type_id),
    PRIMARY KEY (metric_id, system_type_id)
);

CREATE TABLE event_type_system_compat (
    event_type_id  BIGINT NOT NULL REFERENCES event_types(event_type_id),
    system_type_id BIGINT NOT NULL REFERENCES system_types(system_type_id),
    PRIMARY KEY (event_type_id, system_type_id)
);

-- Fact tables
-- NOTE: the strict "UTC, ends with Z" format rule, the no-future-timestamp rule
-- and the 1..5000 atomic batch rule are enforced in ingestion code, not here.
CREATE TABLE telemetry_records (
    telemetry_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    asset_id     BIGINT NOT NULL REFERENCES assets(asset_id),
    metric_id    BIGINT NOT NULL REFERENCES metric_types(metric_id),
    ts           TIMESTAMPTZ NOT NULL,
    value        DOUBLE PRECISION NOT NULL
        CHECK (value NOT IN ('NaN'::double precision,
                             'Infinity'::double precision,
                             '-Infinity'::double precision)),
    UNIQUE (asset_id, metric_id, ts)
);

CREATE TABLE event_records (
    event_id      BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    asset_id      BIGINT NOT NULL REFERENCES assets(asset_id),
    event_type_id BIGINT NOT NULL REFERENCES event_types(event_type_id),
    ts            TIMESTAMPTZ NOT NULL,
    severity      TEXT NOT NULL CHECK (severity IN ('info','warning','critical')),
    details       JSONB,
    UNIQUE (asset_id, event_type_id, ts)
);

-- Alerts (lifecycle: open -> acknowledged -> resolved)
CREATE TABLE alerts (
    alert_id           BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    rule_id            TEXT NOT NULL,
    detection_method   TEXT NOT NULL
        CHECK (detection_method IN ('threshold','anomaly','compound')),
    severity           TEXT NOT NULL CHECK (severity IN ('info','warning','critical')),
    asset_id           BIGINT NOT NULL REFERENCES assets(asset_id),
    title              TEXT NOT NULL,
    summary            TEXT NOT NULL,
    first_ts           TIMESTAMPTZ NOT NULL,
    last_ts            TIMESTAMPTZ NOT NULL,
    detected_ts        TIMESTAMPTZ NOT NULL,
    evidence           JSONB NOT NULL,
    status             TEXT NOT NULL DEFAULT 'open'
        CHECK (status IN ('open','acknowledged','resolved')),
    resolved_ts        TIMESTAMPTZ,
    explanation        JSONB,
    explanation_source TEXT CHECK (explanation_source IN ('ollama','fallback')),
    explained_at       TIMESTAMPTZ,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (last_ts >= first_ts),
    CHECK ((status = 'resolved') = (resolved_ts IS NOT NULL))
);

-- Scenario harness (array columns cannot have foreign keys; validate in code)
CREATE TABLE scenario_runs (
    scenario_run_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    scenario_key    TEXT NOT NULL,
    name            TEXT NOT NULL,
    description     TEXT NOT NULL,
    asset_ids       BIGINT[] NOT NULL,
    start_ts        TIMESTAMPTZ NOT NULL,
    end_ts          TIMESTAMPTZ NOT NULL,
    expected_rules  TEXT[] NOT NULL,
    telemetry_ids   BIGINT[] NOT NULL DEFAULT '{}',
    event_ids       BIGINT[] NOT NULL DEFAULT '{}',
    CHECK (end_ts >= start_ts)
);

-- Indexes (your original 4, plus NEW ones)
CREATE INDEX idx_assets_location    ON assets(location_id);
CREATE INDEX idx_assets_system_type ON assets(system_type_id);
CREATE INDEX idx_telemetry_ts       ON telemetry_records(ts);
CREATE INDEX idx_event_ts           ON event_records(ts);
CREATE INDEX idx_event_asset_ts     ON event_records(asset_id, ts);                  -- NEW
CREATE INDEX idx_alerts_first_ts    ON alerts(first_ts);                             -- NEW
CREATE INDEX idx_alerts_asset_ts    ON alerts(asset_id, first_ts);                   -- NEW
CREATE INDEX idx_alerts_severity    ON alerts(severity);                             -- NEW
CREATE INDEX idx_alerts_open        ON alerts(asset_id) WHERE status <> 'resolved';  -- NEW

COMMIT;

